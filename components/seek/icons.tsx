export type IconKey = keyof typeof ICONS;

/** An icon. Decorative unless you give it a label. */
export function Ic({ n, size = 16, label, className = '' }: { n: IconKey; size?: number; label?: string; className?: string }) {
  const C = ICONS[n];
  return <C size={size} strokeWidth={1.8} className={'lic ' + className} aria-hidden={label ? undefined : true} aria-label={label} role={label ? 'img' : undefined} />;
}

/** A coloured dot for a status: Available, In a meeting, Focus time, Away. */
export function StatusMark({ k }: { k: string }) {
  return <span className={'smark ' + k} aria-hidden="true" />;
}
